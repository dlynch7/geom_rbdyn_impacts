%% dist_to_impact.m
%
% Description:
%   This function computes the signed distance between a rigid body and the
%   ground, as a function of Twb (the configuration of the body frame {b}
%   in the world frame {w}) and a set of parameters that describe the
%   body's geometry. The output of this function takes three possible kinds
%   of values:
%       distance > 0: the body is not in contact with the ground
%       distance = 0: the body is in contact with the ground
%       distance < 0: the body has penetrated into the ground (for a rigid
%                     body and rigid ground, this possibility is not
%                     physical)
%
% Inputs:
%   Twb: configuration of the rigid body's CoM frame {b} relative to the
%        world frame {w}, represented as a 4x4 homogeneous transformation
%        matrix, i.e., an element of SE(3).
%   params: a struct with many fields, including geometry parameters,
%        generated by calling init_params().
%
% Outputs:
%   signed_dist: the signed distance between the rigid body and the ground,
%        with positive values indicating non-contact, zero indicating
%        contact, and negative values indicating interpenetration.

function signed_dist = dist_to_impact(Twb,params)

switch params.body_name
    case 'ellipsoid'
        R_wb = Twb(1:3,1:3); % orientation of {b} in {w}
        p_wb = Twb(1:3,4); % position of {b} origin in {w}
        z_hat_w = [0;0;1]; % unit vector in world-frame +z direction ("up")
        n_hat = -z_hat_w;  % unit vector normal to bottom-most point on 
                           % ellipsoid surface
        D_inv = diag([params.geom.ellipsoid.semi_axes.a^2;
                      params.geom.ellipsoid.semi_axes.b^2;
                      params.geom.ellipsoid.semi_axes.c^2]);
        t1 = R_wb*D_inv*transpose(R_wb)*n_hat; % intermediate variable
        t2 = transpose(n_hat)*t1;             % intermediate variable
        signed_dist = transpose(z_hat_w)*(p_wb + t1/sqrt(t2));
    otherwise
        error('Collision detection not implemented for params.body_name = %s.',...
            params.body_name);
end

end