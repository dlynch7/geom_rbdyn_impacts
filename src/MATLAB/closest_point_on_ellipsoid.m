%% closest_point_on_ellipsoid.m
%
% Description:
%   This function computes pwc, the location in the world frame {w} of the
%   point c on an ellipsoid that is closest to the plane, as a function of
%   Twb (the configuration of the body frame {b} in the world frame {w})
%   and a set of parameters that describe the body's geometry.
%
% Inputs:
%   Twb: configuration of the rigid body's CoM frame {b} relative to the
%        world frame {w}, represented as a 4x4 homogeneous transformation
%        matrix, i.e., an element of SE(3).
%   params: a struct with many fields, including geometry parameters,
%        generated by calling init_params().
%
% Outputs:
%   pwc: the location of the point on the ellipsoid closest to the plane
%        defined by a unit normal vector and a point, both of which are
%        contained in "params"

function pwc = closest_point_on_ellipsoid(Twb,params)

switch params.body_name
    case 'ellipsoid'
        Rwb = Twb(1:3,1:3); % orientation of {b} in {w}
        pwb = Twb(1:3,4); % position of {b} origin in {w}
        n = params.geom.plane.unit_normal;
        D_inv = diag([params.geom.ellipsoid.semi_axes.a^2;
                      params.geom.ellipsoid.semi_axes.b^2;
                      params.geom.ellipsoid.semi_axes.c^2]);
        t1 = Rwb*D_inv*transpose(Rwb)*n;
        t2 = transpose(n)*t1;
        pwc = pwb - t1/sqrt(t2);
    otherwise
        error('Collision detection not implemented for params.body_name = %s.',...
            params.body_name);
end

end