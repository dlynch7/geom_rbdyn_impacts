%% impact_map.m
%
% Description:
%   This function maps the ellipsoid's pre-impact state to the post-impact
%   state. The configuration Twb is unchanged but the twist Vb can have a
%   jump discontinuity. The impact map is derived from conservation of
%   momentum and conservation of energy.
%
% Inputs:
%   Twb_pre: pre-impact configuration of the rigid body's CoM frame {b}
%       relative to the world frame {w}, represented as a 4x4 homogeneous
%       transformation matrix, i.e., an element of SE(3).
%   Vb_pre: pre-impact body twist, represented by a 6x1 vector whose 
%       elements are the components of an element of se(3).
%   Twc: configuration of contact frame {c} relative to world frame {w},
%       represented as a 4x4 homogeneous transformation matrix, i.e., an
%       element of SE(3).
%   Fb: net external body wrench, represented by a 6x1 vector whose
%       elements are the components of an element of dse(3), the dual space
%       to se(3).
%   params: a struct with many fields, including inertial parameters,
%       generated by calling init_params().
%
% Outputs:
%   Twb_post: post-impact configuration of the rigid body's CoM frame {b}
%       relative to the world frame {w}, represented as a 4x4 homogeneous
%       transformation matrix, i.e., an element of SE(3).
%   Vb_post: post-impact body twist, represented by a 6x1 vector whose 
%       elements are the components of an element of se(3).
%   impulse_mag (optional): magnitude of impulse acting perpendicular to the
%       impact surface.

function [Twb_post,Vb_post,varargout] = impact_map(Twb_pre,...
                                                   Vb_pre,...
                                                   Twc,...
                                                   Fb,...
                                                   params)

    % configuration doesn't change during impact:
    Twb_post = Twb_pre;

    % set up initial guess:
    Vb_post_0 = zeros(6,1);
    imp_mag_0 = params.dyn.mass*params.dyn.grav;
    x0 = [Vb_post_0;imp_mag_0];
    
    % set bounds:
    lb = [-Inf*ones(6,1);-Inf]; % bound impulse below at zero
    
    % call fmincon:
    options = optimoptions('fmincon','display','none',...
                           'ConstraintTolerance',1e-12,...
                           'Algorithm','sqp');
    fminconstr = @(x) impact_sys_eq(x,Vb_pre,Twb_pre,Twc,params);
    [x,~,exitflag] = fmincon(@(x)0,x0,[],[],[],[],lb,[],fminconstr,options);
    if exitflag <= 0
        error('Failed to solve impact map.');
    end
    x = x(:); % ensure column vector
    
    % unpack solution
    Vb_post = x(1:6);
    impulse_mag = x(7);
    
    fprintf('\tE after impact: %f\n',...
        params.dyn.mass*params.dyn.grav*Twb_pre(3,4) + ...
        0.5*Vb_post'*params.dyn.spatial_inertia_matrix_CoM*Vb_post)
    
    varargout{1} = impulse_mag;
end

%% Helper function: return residual of system of impact equations
%
% Description:
%
% Inputs:
%   x: 7x1 vector with the following components:
%       x(1:6): post-impact body twist:
%           x(1:3): angular body twist components
%           x(4:6): linear body twist components
%       x(7):   magnitude of contact impulse during impact
%
% Outputs:
%   res_ineq: simply []
%   res: 7x1 residual vector with the following components:
%       res(1:6): impulse-momentum residual
%       res(7):   energy residual

function [res_ineq,res_eq] = impact_sys_eq(x,Vb_pre,Twb,Twc,params)

    Vb_post = x(1:6);
    imp_mag = x(7);
    
    % compute Tcb given Twc and Twb:
    Tcb = TransInv(Twc)*Twb;
    
    % contact wrench is just force_mag in z_c direction:
    Fc = [zeros(5,1);imp_mag];

    Gb = params.dyn.spatial_inertia_matrix_CoM; % spatial inertia matrix in {b}
    
    % net wrench in {b} frame:
    Fb_net = transpose(Adjoint(Tcb))*Fc;
    
    % conservation of momentum:
    momentum_res = Gb*(Vb_post - Vb_pre) - Fb_net;
    
    % conservation of energy:
    KE_pre= transpose(Vb_pre)*Gb*Vb_pre;
    KE_post= transpose(Vb_post)*Gb*Vb_post;
    KE_res = KE_post - KE_pre;
    
    res_eq = [momentum_res;KE_res];
    res_ineq = [];

end