%% impact_map.m
%
% Description:
%   This function maps the ellipsoid's pre-impact state to the post-impact
%   state. The configuration Twb is unchanged but the twist Vb can have a
%   jump discontinuity. The impact map is derived from conservation of
%   momentum and conservation of energy.
%
% Inputs:
%   Twb_pre: pre-impact configuration of the rigid body's CoM frame {b}
%       relative to the world frame {w}, represented as a 4x4 homogeneous
%       transformation matrix, i.e., an element of SE(3).
%   Vb_pre: pre-impact body twist, represented by a 6x1 vector whose 
%       elements are the components of an element of se(3).
%   Twc: configuration of contact frame {c} relative to world frame {w},
%       represented as a 4x4 homogeneous transformation matrix, i.e., an
%       element of SE(3).
%   Fb: net external body wrench, represented by a 6x1 vector whose
%       elements are the components of an element of dse(3), the dual space
%       to se(3).
%   params: a struct with many fields, including inertial parameters,
%       generated by calling init_params().
%
% Outputs:
%   Twb_post: post-impact configuration of the rigid body's CoM frame {b}
%       relative to the world frame {w}, represented as a 4x4 homogeneous
%       transformation matrix, i.e., an element of SE(3).
%   Vb_post: post-impact body twist, represented by a 6x1 vector whose 
%       elements are the components of an element of se(3).
%   impulse_mag (optional): magnitude of impulse acting perpendicular to the
%       impact surface.

function [Twb_post,Vb_post,varargout] = impact_map(Twb_pre,...
                                                   Vb_pre,...
                                                   Twc,...
                                                   params)

    % configuration doesn't change during impact:
    Twb_post = Twb_pre;

    % compute Tcb given Twc and Twb:
    Tcb = TransInv(Twc)*Twb_pre;

    % form spatial inertia matrix in {b} and its inverse:
    Gb = params.dyn.spatial_inertia_matrix_CoM; % spatial inertia matrix in {b}
    Gb_inv = diag(1./diag(Gb)); % no need to call inv() to compute Gb_inv
    
    % compute impulse magnitude:
    n6_c = [zeros(5,1);1]; % contact normal 6-vector in {c}
    n6_b = transpose(Adjoint(Tcb))*n6_c;
    t1 = (1 + params.dyn.restitution_coefficient) ...
       * transpose(n6_b)*Vb_pre;
    t2 = transpose(n6_b)*Gb_inv*n6_b;
    impulse_mag = -t1/t2;
    impulse_b = impulse_mag*n6_b; % impulse 6-vector in {b}
    
    % compute post-impact body twist using momentum conservation:
    Vb_post = Gb_inv*(Gb*Vb_pre + impulse_b);
    
    varargout{1} = impulse_mag;
end